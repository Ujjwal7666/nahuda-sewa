CREATE TABLE `programs` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `revision` INTEGER NOT NULL DEFAULT 1,
  `title_en` VARCHAR(200) NOT NULL,
  `title_ne` VARCHAR(200) NOT NULL,
  `slug` VARCHAR(120) NOT NULL,
  `full_description_en` LONGTEXT NOT NULL,
  `full_description_ne` LONGTEXT NOT NULL,
  `description_format` VARCHAR(10) NOT NULL DEFAULT 'HTML',
  `additional_heading_en` VARCHAR(200) NOT NULL,
  `additional_heading_ne` VARCHAR(200) NOT NULL,
  `additional_content_en` TEXT NOT NULL,
  `additional_content_ne` TEXT NOT NULL,
  `featured_image_id` INTEGER NULL,
  `display_order` INTEGER NOT NULL DEFAULT 0,
  `is_active` BOOLEAN NOT NULL DEFAULT false,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `programs_slug_key` (`slug`),
  INDEX `programs_is_active_display_order_id_idx` (`is_active`,`display_order`,`id`),
  CONSTRAINT `programs_order_check` CHECK (`display_order` BETWEEN 0 AND 999999),
  CONSTRAINT `programs_description_format_check` CHECK (`description_format` IN ('HTML','PLAIN')),
  CONSTRAINT `programs_featured_image_id_fkey` FOREIGN KEY (`featured_image_id`) REFERENCES `media_assets` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
